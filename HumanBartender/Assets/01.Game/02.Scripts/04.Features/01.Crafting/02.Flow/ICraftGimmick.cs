using System.Threading;
using Cysharp.Threading.Tasks;

/// <summary>
/// 제조 기믹 하나가 구현하는 인터페이스. 병따기·따르기·셰이크·스터가 각자의 방식으로 이걸 채운다.
///
/// 기존 IMiniGameController는 시작·완료·다음 버튼·서빙이 따로 흩어져 있고, 끝났다는 신호가
/// 컷씬 재생과 얽혀 있었다. 여기서는 "이 스텝을 플레이하고 결과를 돌려준다" 하나로 줄인다.
/// 기믹은 자기 조작만 알면 되고, 큐의 몇 번째인지도 다음에 뭐가 오는지도 몰라도 된다.
///
/// 필업은 따로 구현하지 않는다. 따르기와 조작이 같아서 같은 구현을 쓰고, 스텝의 종류만 다르다.
/// </summary>
public interface ICraftGimmick
{
    /// <summary>
    /// 스텝 하나를 플레이하고 확정된 결과를 돌려준다.
    ///
    /// 언제 끝나는지는 기믹이 정한다. 따르기·필업은 플레이어가 다음 버튼을 누를 때, 셰이크·스터는
    /// 목표 스택을 채우거나 다음 버튼을 누를 때, 병따기는 병뚜껑이 열릴 때다.
    /// </summary>
    /// <param name="step">무엇을 다루고 목표가 얼마인지. 목표가 없으면 화면에 ???로 보여준다.</param>
    /// <param name="context">
    /// 이번 시도 전체의 사정 — 고른 잔·도구·재료. 스텝에는 재료 하나만 들어 있어서 잔을 알 길이 없는데,
    /// 어느 잔에 따르고 어느 잔을 흔드는지는 모든 기믹이 알아야 한다. 읽기만 한다.
    /// </param>
    /// <param name="timer">
    /// 한 잔 전체의 시계. 결과에 확정 시점을 적기 위해 읽는다. 기믹이 이 시계를 멈추거나
    /// 되돌리지는 않는다 — 시계는 제조 전체의 것이지 기믹의 것이 아니다.
    /// </param>
    UniTask<GimmickResult> PlayAsync(GimmickStep step, CraftContext context,
                                    CraftTimer timer, CancellationToken token);

    /// <summary>
    /// 지금 플레이어의 입력을 받아 판정에 반영하고 있는지.
    ///
    /// 한 잔의 제조시간은 이 시간만 더한다. 성공 연출을 보는 동안, 다음 기믹으로 넘어가는 동안,
    /// 결과 화면을 기다리는 동안은 플레이어가 할 수 있는 일이 없어서 시간에 넣지 않는다 —
    /// 손이 굼떠서 늦은 것과 연출이 길어서 늦은 것을 같이 세면 실력을 재는 값이 아니게 된다.
    ///
    /// 선택이 아니라 필수다. 답하지 않는 기믹이 있으면 그 기믹만 공짜 시간을 갖게 된다.
    /// </summary>
    bool IsManualInputActive { get; }
}
